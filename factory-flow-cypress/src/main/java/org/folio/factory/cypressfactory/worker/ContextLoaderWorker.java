    // Area detection
    // -------------------------------------------------------------------------

    private List<String> detectAreas(JsonNode metadata, String body) {
        List<String> areas = new ArrayList<>();

        String issueKey = metadata.path("issue_key").asString("").trim();
        if (!issueKey.isBlank()) {
            int dash = issueKey.indexOf('-');
            String prefix = dash > 0 ? issueKey.substring(0, dash) : issueKey;
            List<String> keyAreas = PROJECT_KEY_AREAS.get(prefix.toUpperCase());
            if (keyAreas != null) {
                log.info("Area(s) {} detected from project key prefix '{}'", keyAreas, prefix);
                areas.addAll(keyAreas);
            }
        }

        if (areas.size() < MAX_AREAS) {
            String searchText = buildSearchText(metadata, body);
            for (Map.Entry<String, String> entry : AREA_KEYWORDS) {
                if (areas.size() >= MAX_AREAS) break;
                String area = entry.getValue();
                if (!areas.contains(area) && searchText.contains(entry.getKey())) {
                    areas.add(area);
                }
            }
        }

        return areas.isEmpty() ? List.of("generic") : areas;
    }

    private String buildSearchText(JsonNode metadata, String body) {
        StringBuilder sb = new StringBuilder();
        appendJsonText(sb, metadata.path("summary"));
        appendJsonText(sb, metadata.path("components"));
        appendJsonText(sb, metadata.path("analysis"));
        if (body != null) sb.append(' ').append(body.toLowerCase());
        return sb.toString();
    }

    private void appendJsonText(StringBuilder sb, JsonNode node) {
        if (node.isArray()) {
            for (JsonNode element : node) {
                sb.append(' ').append(element.asString("").toLowerCase());
            }
        } else if (!node.isMissingNode() && !node.isNull()) {
            sb.append(' ').append(node.asString("").toLowerCase());
        }
    }

    // -------------------------------------------------------------------------
    // Context fetching
    // -------------------------------------------------------------------------

    private String fetchContexts(List<String> areas) {
        if (areas.size() == 1) return fetchContext(areas.get(0));
        StringBuilder combined = new StringBuilder();
        for (String area : areas) {
            combined.append(fetchContext(area)).append("\n\n");
        }
        return combined.toString().trim();
    }

    private String fetchContext(String area) {
        if (properties.folioAiRepo().isBlank()) {
            log.info("FACTORY_CYPRESS_FOLIO_AI_REPO not configured - context.md will be empty");
            return buildEmptyContext(area);
        }
        String path = CONTEXT_PATH_PREFIX + area + ".md";
        String content = gitHub.getFileContent(properties.folioAiRepo(), BRANCH, path);
        if (content == null || content.isBlank()) {
            log.info("No context file for area '{}' at {}/{} in {}", area, BRANCH, path,
                    properties.folioAiRepo());
        }
        return content != null && !content.isBlank() ? content : buildEmptyContext(area);
    }

    private String buildEmptyContext(String area) {
        return "# Cypress Context: " + area + "\n\n"
                + "_No area-specific context available. Refer to the scope manifest for guidance._\n";
    }
